// q_d_domain_attestation.go -- a second, genuinely independent administrative domain for the
// obligation-discharge coverage check that S11b (ablation_behavior_safety.go, same day) closed
// for ONE domain only. S11b's fix requires a real on-chain DischargeObligation record bound to
// this same transfer, but that record lives on the SAME Fabric network, under the SAME
// administrative control (this project's own OpenStack deployment), as the decision itself --
// S11b's own "What this does and does not establish" section already discloses this is a
// single-domain check.
//
// This file adds a second, independently-governed co-signer to the discharge-coverage decision:
// a secp256k1 key generated on, and never transmitted off, a separate cloud account (AWS; this
// project's OpenStack deployment runs everywhere else). Given a decision's real content, that
// AWS-side process (qd2aws, a standalone Go program, deliberately NOT importing or calling this
// module's Go code) RE-DERIVES, from scratch, whether the obligation is genuinely covered --
// amount-vs-threshold, the referenced discharge record's own ObligationDischarged flag, the
// confused-deputy binding check, and the mechanism/strength model -- before signing. The
// signature is verified here via secpecdsa.RecoverCompact, the exact pattern already used twice
// in this codebase (lightclient.go's verifyIbft2Header, ablation_a5_quorum.go's
// verifyIbft2HeaderCustomQuorum) for Besu validator commit-seal recovery, applied here to a
// single trusted "AWS domain authority" address instead of a validator set.
//
// What this closes: an adversary who fully controls the OpenStack domain (including a dishonest
// or compromised chaincode admin able to directly manipulate this chain's own ledger state)
// still cannot fabricate AWS's agreement without the AWS-held private key -- the one property
// the first, now-demoted "deployment portability check" experiment (same day) did NOT test,
// because it redeployed the SAME deterministic code with no second key or domain involved at
// all.
//
// What this does NOT close, stated plainly: the AWS side is given the decision's content by an
// orchestrator (it does not independently query the main chain's ledger itself over a direct
// network path) and re-validates that content's internal logic/consistency, rather than
// independently re-deriving the underlying evidence from first principles. It therefore defends
// against (a) forged/absent AWS agreement and (b) a single buggy/compromised domain's logic
// error that an independently-written second implementation would catch -- not against an
// orchestrator that lies to BOTH domains identically, nor against compromise of both domains at
// once.
package chaincode

import (
	"encoding/json"
	"fmt"
	"math/big"

	secpecdsa "github.com/decred/dcrd/dcrec/secp256k1/v4/ecdsa"
	"github.com/hyperledger/fabric-contract-api-go/v2/contractapi"
)

// awsDomainAuthorityAddress is the Ethereum-style address (keccak256(uncompressed pubkey)[12:])
// derived from a secp256k1 key generated by `qd2aws keygen` on a separate AWS account/instance
// on 2026-10-08; the corresponding private key was never transmitted off that machine. Same
// hardcoded-trust-anchor pattern as pinnedValidatorHex (lightclient.go) and
// policyAuthorityAddress (commit.go).
const awsDomainAuthorityAddress = "0x6ad6b3ee6b4db60c28eb9de1b73945371ffcc063"

// verifyAwsDomainAttestation recovers the signer of a 65-byte compact signature (same layout as
// lightclient.go's commit-seal recovery: compact[0]=27+recoveryID, compact[1:33]=r,
// compact[33:65]=s) over the given digest, and reports whether it matches the pinned AWS domain
// authority.
func verifyAwsDomainAttestation(compactSigHex string, digest []byte) (bool, string, error) {
	sig, err := unhexBytes(compactSigHex)
	if err != nil || len(sig) != 65 {
		return false, "", fmt.Errorf("aws attestation signature must be 65 bytes of hex, got %d bytes", len(sig))
	}
	pub, _, err := secpecdsa.RecoverCompact(sig, digest)
	if err != nil {
		return false, "", fmt.Errorf("aws attestation signature recovery failed: %v", err)
	}
	addr := keccak256(pub.SerializeUncompressed()[1:])[12:]
	want, err := unhexBytes(awsDomainAuthorityAddress)
	if err != nil {
		return false, "", err
	}
	recovered := "0x" + fmt.Sprintf("%x", addr)
	if new(big.Int).SetBytes(addr).Cmp(new(big.Int).SetBytes(want)) != 0 {
		return false, recovered, nil
	}
	return true, recovered, nil
}

// awsAttestationDigest reproduces exactly the digest qd2aws's verify-sign subcommand signs:
// keccak256(decisionID || obligationDischargeRef || sourceDomain || role || amount(8B BE) ||
// passedByte). Both sides must agree on this byte layout or recovery fails even for a genuine
// signature -- this exact scheme is also embedded in qd2aws's own source
// (~/paper_backups/submit_paper2/evidence/qd2_domain_attestation_2026-10-08.md documents both
// sides together).
func awsAttestationDigest(decisionID, obligationDischargeRef, sourceDomain, role string, amount int64, passed bool) []byte {
	amountBytes := make([]byte, 8)
	for i := 0; i < 8; i++ {
		amountBytes[7-i] = byte(amount >> (8 * i))
	}
	passedByte := byte(0x00)
	if passed {
		passedByte = 0x01
	}
	return keccak256([]byte(decisionID), []byte(obligationDischargeRef), []byte(sourceDomain), []byte(role), amountBytes, []byte{passedByte})
}

// SubmitDecisionTrustlessV7ObligationDomainVerified is additive: it changes neither
// SubmitDecisionTrustlessV7ObligationVerifiedDischarge (ablation_behavior_safety.go, same day)
// nor any earlier entry point. It re-runs that function's exact evidence-chain,
// discharge-reference, and obligation-model pipeline unchanged, and additionally requires a
// valid signature from the pinned AWS domain authority over an attestation that it independently
// re-derived the same "covered" verdict. Both domains must agree; either one's absence or
// mismatch is REJECT.
func (c *AuthContract) SubmitDecisionTrustlessV7ObligationDomainVerified(ctx contractapi.TransactionContextInterface,
	decisionID string, sourceDomain string, role string, amount int64, sourceLimit int64,
	codeHash string, proofJSON string, publicSignalsJSON string,
	headerJSON string, registryProofJSON string, featureProofJSON string,
	obligationProfile string, mappedMechanism string, obligationDischargeRef string, enforcementWitnessVerified bool,
	awsAttestedPassed bool, awsCompactSigHex string) (string, error) {

	exists, err := c.decisionExists(ctx, decisionID)
	if err != nil {
		return "", err
	}
	if exists {
		return "", fmt.Errorf("decision %s already recorded (replay rejected)", decisionID)
	}
	if amount <= 0 {
		return "", fmt.Errorf("amount must be positive (got %d)", amount)
	}
	ch, err := unhexBytes(codeHash)
	if err != nil || len(ch) != 32 {
		return "", fmt.Errorf("codeHash must be 32 bytes of hex")
	}

	// -- real evidence chain, identical to SubmitDecisionTrustlessV7Obligation/
	// SubmitDecisionTrustlessV7ObligationVerifiedDischarge --
	zkOK, zkDetail, err := verifySemBoundProof(proofJSON, publicSignalsJSON)
	if err != nil {
		return "", fmt.Errorf("malformed verification request: %v", err)
	}
	var pub []string
	_ = json.Unmarshal([]byte(publicSignalsJSON), &pub)
	if zkOK && len(pub) != 7 {
		zkOK = false
		zkDetail = fmt.Sprintf("SubmitDecisionTrustlessV7ObligationDomainVerified requires a v7 proof (7 public signals: adds featureHash), got %d", len(pub))
	}
	if zkOK {
		bound, ok := new(big.Int).SetString(pub[1], 10)
		if !ok || bound.Cmp(new(big.Int).SetBytes(ch)) != 0 {
			zkOK = false
			zkDetail = "proof verifies but its public solidityCodeHash differs from this decision's codeHash (proof substitution rejected)"
		}
	}

	nowSec, err := ledgerNow(ctx)
	if err != nil {
		return "", err
	}
	src := verifySourceState(nowSec, ch, headerJSON, registryProofJSON)

	featureOK, featureDetail := false, "source header not verified, so no feature commitment could be proven"
	if src.Verified {
		if len(pub) == 7 {
			featureOK, featureDetail = verifyFeatureBinding(src.StateRoot, ch, featureProofJSON, pub[6])
		} else {
			featureDetail = "no v7 public featureHash signal present"
		}
	}

	semBound := zkOK && src.Verified && src.MlPassed && featureOK
	evOK := src.Verified && src.Approvals >= minApprovals
	detail := zkDetail
	if zkOK && src.Verified && !src.MlPassed {
		detail = "proof is valid and bound, but the registry's proven mlScanPassed[codeHash] is false"
	} else if zkOK && src.Verified && src.MlPassed {
		detail = featureDetail
	}

	// -- real, on-chain-verified discharge (S11b, same day) --
	obligationDischarged := false
	dischargeDetail := "no obligationDischargeRef supplied (treated as not discharged)"
	if obligationDischargeRef != "" {
		refData, refErr := ctx.GetStub().GetState(obligationDischargeRef)
		if refErr != nil {
			return "", fmt.Errorf("failed to read referenced obligation record: %v", refErr)
		}
		if refData == nil {
			dischargeDetail = fmt.Sprintf("referenced obligation record %q does not exist on-chain", obligationDischargeRef)
		} else {
			var ref PortableDecisionRecord
			if err := json.Unmarshal(refData, &ref); err != nil {
				return "", fmt.Errorf("referenced obligation record %q is malformed: %v", obligationDischargeRef, err)
			}
			usedKey := "discharge-used:" + obligationDischargeRef
			usedData, usedErr := ctx.GetStub().GetState(usedKey)
			if usedErr != nil {
				return "", fmt.Errorf("failed to read discharge-use marker: %v", usedErr)
			}
			switch {
			case !ref.ObligationDischarged:
				dischargeDetail = fmt.Sprintf("referenced record %q exists but was never actually discharged on-chain (ObligationDischarged=false)", obligationDischargeRef)
			case ref.SourceDomain != sourceDomain || ref.Role != role || ref.Amount != amount:
				dischargeDetail = fmt.Sprintf("referenced record %q was discharged, but for a different transfer (sourceDomain/role/amount mismatch) -- cannot cover this decision (confused-deputy rejected)", obligationDischargeRef)
			case usedData != nil:
				// Red-team finding (2026-10-08): a single real discharge, unbound, could be cited
				// by unlimited distinct decisionIDs sharing the same (sourceDomain,role,amount).
				// A real discharge now covers exactly one citing decision, ever.
				dischargeDetail = fmt.Sprintf("referenced record %q was already consumed by decision %q (one discharge covers one decision; re-citation rejected)", obligationDischargeRef, string(usedData))
			default:
				obligationDischarged = true
				dischargeDetail = fmt.Sprintf("referenced record %q verified on-chain: genuinely discharged for this same sourceDomain/role/amount", obligationDischargeRef)
			}
		}
	}

	oblCovered, oblDetail := oblCoveredV2(obligationProfile, mappedMechanism, obligationDischarged, enforcementWitnessVerified)
	oblDetail = oblDetail + " [discharge: " + dischargeDetail + "]"

	// -- second, independent domain: AWS co-signature over its OWN independently-derived verdict --
	digest := awsAttestationDigest(decisionID, obligationDischargeRef, sourceDomain, role, amount, awsAttestedPassed)
	awsOK, awsSigner, awsErr := verifyAwsDomainAttestation(awsCompactSigHex, digest)
	if awsErr != nil {
		awsOK = false
		oblDetail = oblDetail + fmt.Sprintf(" [aws domain: signature error: %v]", awsErr)
	} else if !awsOK {
		oblDetail = oblDetail + fmt.Sprintf(" [aws domain: signature recovered to %s, not the pinned AWS domain authority %s]", awsSigner, awsDomainAuthorityAddress)
	} else if !awsAttestedPassed {
		oblDetail = oblDetail + " [aws domain: genuine AWS signature, but AWS's own independent re-derivation said NOT covered]"
	} else {
		oblDetail = oblDetail + fmt.Sprintf(" [aws domain: genuine signature from %s, independently re-derived covered=true]", awsSigner)
	}
	// Both domains must agree that the obligation is covered: this chain's own check (oblCovered)
	// AND a genuine, matching-verdict AWS signature (awsOK && awsAttestedPassed).
	bothDomainsCovered := oblCovered && awsOK && awsAttestedPassed

	threshold, known := RoleThreshold[role]
	if !known {
		threshold = 0
	}

	var class string
	switch {
	case !semBound:
		class = "REJECT" // Theorem T0: unbound semantic relation, no evidence/obligation level compensates
	case !evOK:
		class = "REJECT"
	case !known:
		class = "REEVALUATE"
	case amount > threshold:
		class = "REJECT" // widening: amount exceeds what the destination permits
	case !bothDomainsCovered:
		class = "REJECT" // S5/S6/S7, an unverified/mismatched discharge claim, OR the second domain disagreed/was absent/forged
	default:
		class = "SAFE"
	}

	rec := PortableDecisionRecord{
		DecisionID: decisionID, SourceDomain: sourceDomain, Role: role, Amount: amount,
		SourceLimit: sourceLimit, SemBound: semBound, EvAssuranceOK: evOK, TransferClass: class,
		DestThreshold: threshold, ZKVerified: true, ZKVerificationDetail: detail,
		CodeHash: codeHash, LCVerified: src.Verified, LCDetail: src.Detail,
		SourceBlockNumber: src.BlockNumber, SourceBlockHash: src.BlockHash,
		ProvenApprovals: src.Approvals, ProvenMlScanPassed: src.MlPassed,
		ObligationProfile: obligationProfile, MappedMechanism: mappedMechanism,
		ObligationCoveredV2: bothDomainsCovered, ObligationDetailV2: oblDetail, ObligationV2Checked: true,
		AwsDomainVerified: awsOK && awsAttestedPassed, AwsDomainSigner: awsSigner,
	}
	recJSON, err := json.Marshal(rec)
	if err != nil {
		return "", err
	}
	if err := ctx.GetStub().PutState(decisionID, recJSON); err != nil {
		return "", fmt.Errorf("failed to write state: %v", err)
	}
	if obligationDischarged && obligationDischargeRef != "" {
		if err := ctx.GetStub().PutState("discharge-used:"+obligationDischargeRef, []byte(decisionID)); err != nil {
			return "", fmt.Errorf("failed to write discharge-use marker: %v", err)
		}
	}
	return class, nil
}
